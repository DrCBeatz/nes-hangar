"""Static title and control guide built from the existing NES font tiles."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path


def write_assets(build, font, preview_dir=None):
    """Write one nametable/palette, metadata and optional decoded PNG previews.

    The caller has already generated fixed-patterns.bin. No CHR patterns,
    sprite artwork, controller state or gameplay data are changed here.
    """
    build = Path(build)
    build.mkdir(parents=True, exist_ok=True)
    name = bytearray(1024)
    lines = []

    def line(row, text, palette=1):
        col = (32-len(text))//2
        assert 0 <= row < 30 and 0 <= col and col+len(text) <= 32
        missing = set(text)-set(font)
        assert not missing, ('Unsupported title glyphs', sorted(missing))
        name[row*32+col:row*32+col+len(text)] = bytes(font[c] for c in text)
        lines.append(dict(row=row, col=col, text=text, palette=palette))
        for x in range(col, col+len(text)):
            addr = 0x3c0+(row//4)*8+x//4
            shift = ((row & 2) << 1) | (x & 2)
            name[addr] = (name[addr] & ~(3 << shift)) | (palette << shift)

    line(3, 'HANGAR', 2)
    line(5, 'NES FPS PROTOTYPE', 3)
    line(8, 'CONTROLS', 3)
    line(10, 'UP/DOWN WALK')
    line(12, 'LEFT/RIGHT TURN')
    line(14, 'A+LEFT/RIGHT STRAFE')
    line(16, 'B FIRE')
    line(18, 'A USE DOOR / SWITCH')
    line(20, 'START PAUSE / RESUME')
    line(22, 'SELECT EDGE COMPARISON')
    line(26, 'PRESS START TO PLAY')

    assert 4 not in name[:960], 'Reclaimed blank tile belongs to the pistol'
    used_tiles = sorted(set(name[:960]))
    assert set(used_tiles) <= set(font.values()), 'Title must use existing font only'
    # The established black/brown world colors remain palette0. White guide
    # text, a warm amber heading, and gray secondary labels use the existing
    # fixed font's first opaque color. Sprite palettes are irrelevant here.
    palette = bytes([0x0f,0x17,0x07,0x2d, 0x0f,0x30,0x10,0x2d,
                     0x0f,0x27,0x17,0x2d, 0x0f,0x10,0x00,0x2d]*2)
    (build/'title-nametable.bin').write_bytes(name)
    (build/'title-palette.bin').write_bytes(palette)
    config = dict(TITLE_NAMETABLE_ADDR=0x2000, TITLE_PATTERN_TABLE=0,
                  TITLE_START_ROW=26)
    (build/'title-config.inc').write_text(
        ''.join(f'{key} = ${value:04X}\n' for key,value in config.items()))
    report = dict(lines=lines, addresses=config, palette=list(palette),
                  fontMap=font, usedFontTiles=used_tiles, nametable=0,
                  patternTable=0, spriteRendering=False, additionalPatternBytes=0,
                  guideScope='Existing controls; Select retains the edge-rendering comparison',
                  sha256={filename:hashlib.sha256((build/filename).read_bytes()).hexdigest()
                          for filename in ('title-nametable.bin','title-palette.bin','title-config.inc')})
    if preview_dir is not None:
        report['preview'] = _previews(Path(preview_dir), build/'fixed-patterns.bin', name, palette)
    (build/'title-layout.json').write_text(json.dumps(report, indent=2)+'\n')
    return report


def _previews(directory, patterns_path, name, palette):
    """Decode the exact generated bytes; this is an offline preview, not Mesen."""
    patterns = Path(patterns_path).read_bytes()
    assert len(patterns) == 1024, 'Expected the existing 64 fixed patterns'
    rgb = {0x0f:(0,0,0), 0x17:(102,52,0), 0x07:(80,20,0),
           0x2d:(78,78,78), 0x30:(255,255,255), 0x10:(152,150,152),
           0x27:(234,158,34), 0x00:(98,98,98)}
    pixels = [[(0,0,0)]*256 for _ in range(240)]
    for tile_y in range(30):
        for tile_x in range(32):
            tile_id = name[tile_y*32+tile_x]
            assert tile_id < 64
            tile = patterns[tile_id*16:tile_id*16+16]
            attr = name[0x3c0+(tile_y//4)*8+tile_x//4]
            pal_id = (attr >> (((tile_y & 2) << 1) | (tile_x & 2))) & 3
            for py in range(8):
                for px in range(8):
                    color = ((tile[py] >> (7-px)) & 1) | (((tile[py+8] >> (7-px)) & 1) << 1)
                    palette_index = palette[0 if color == 0 else pal_id*4+color]
                    pixels[tile_y*8+py][tile_x*8+px] = rgb[palette_index]
    directory.mkdir(parents=True, exist_ok=True)
    native = directory/'title-native.png'
    enlarged = directory/'title-preview.png'
    try:
        from PIL import Image
    except ModuleNotFoundError:
        # Existing project builders need no image-library installation. Keep
        # the exact same decoded pixels when Pillow is unavailable locally.
        import struct
        import zlib
        def save_png(path, scale):
            def chunk(kind, payload):
                return (struct.pack('>I',len(payload))+kind+payload+
                        struct.pack('>I',zlib.crc32(kind+payload)))
            scanlines=[]
            for row in pixels:
                scanline=b'\0'+b''.join(bytes(pixel)*scale for pixel in row)
                scanlines.extend([scanline]*scale)
            header=struct.pack('>IIBBBBB',256*scale,240*scale,8,2,0,0,0)
            path.write_bytes(b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',header)+
                             chunk(b'IDAT',zlib.compress(b''.join(scanlines),9))+
                             chunk(b'IEND',b''))
        save_png(native,1)
        save_png(enlarged,3)
    else:
        screen = Image.frombytes('RGB',(256,240),b''.join(bytes(p) for row in pixels for p in row))
        screen.save(native)
        screen.resize((768,720),Image.Resampling.NEAREST).save(enlarged)
    return dict(native=str(native), enlarged=str(enlarged),
                source='Offline decode of generated nametable, palette and existing fixed-pattern bytes',
                nativeSize=[256,240], previewScale=3, colorApproximation='Representative NES RGB palette')
